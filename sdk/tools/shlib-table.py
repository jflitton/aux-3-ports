#!/usr/bin/env python3
"""Write the linker script that gives each entry point of A/UX's shared C library its
address, from A/UX's own files.

  shlib-table.py LIBC_S.A LIBC1_S... > sdk/lib/libc1_s.ld

LIBC_S.A is /lib/libc_s.a from A/UX 3.1, the library A/UX's ld links programs with: it
gives each entry point of /shlib/libc1_s as an absolute symbol. Each LIBC1_S is
/shlib/libc1_s from an A/UX version the programs should run on (3.0, 3.0.1, 3.1). An
entry point goes in the script only if every one of them has it at that address: a
function as a jmp in the library's branch table, data as a symbol of that name. The
script uses PROVIDE, so a definition of our own wins.
"""
import re, struct, sys

BRANCH_TABLE = 0x47f00000  # where the shared library's text starts
SHLIB_DATA = 0x47fc0000    # and its data


def ar_members(data):
    if data[:8] != b'!<arch>\n':
        sys.exit('shlib-table: not an archive')
    off = 8
    while off + 60 <= len(data):
        name = data[off:off + 16].decode('latin-1').strip().rstrip('/')
        size = int(data[off + 48:off + 58])
        yield name, data[off + 60:off + 60 + size]
        off += 60 + size + (size & 1)


def coff_symbols(obj):
    """(name, value, section number) of each external symbol of a COFF file."""
    magic, nscns, _, symptr, nsyms = struct.unpack('>HHiii', obj[:16])
    if magic != 0x150:
        return
    strtab = symptr + 18 * nsyms
    i = 0
    while i < nsyms:
        e = obj[symptr + 18 * i:symptr + 18 * (i + 1)]
        if e[:4] == b'\0\0\0\0':
            o = strtab + struct.unpack('>I', e[4:8])[0]
            name = obj[o:obj.index(b'\0', o)]
        else:
            name = e[:8].rstrip(b'\0')
        value, scnum, _, sclass, numaux = struct.unpack('>ihHBB', e[8:18])
        if sclass == 2:
            yield name.decode('latin-1'), value & 0xffffffff, scnum
        i += 1 + numaux


def text_section(obj):
    nscns, = struct.unpack('>H', obj[2:4])
    opthdr, = struct.unpack('>H', obj[16:18])
    for i in range(nscns):
        h = obj[20 + opthdr + 40 * i:20 + opthdr + 40 * (i + 1)]
        if h[:8].rstrip(b'\0') == b'.text':
            vaddr, size, ptr = struct.unpack('>iii', h[12:24])
            return vaddr, size, ptr
    sys.exit('shlib-table: no .text in the shared library')


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__.strip().split('\n\n')[1])
    entries = {}
    for _, obj in ar_members(open(sys.argv[1], 'rb').read()):
        for name, value, scnum in coff_symbols(obj):
            if scnum == -1 and re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', name) \
                    and not re.fullmatch(r'lb\d+', name):
                entries[name] = value
    libs = []
    for path in sys.argv[2:]:
        lib = open(path, 'rb').read()
        syms = {}
        for name, value, scnum in coff_symbols(lib):
            if scnum > 0:
                syms.setdefault(name, value)
        libs.append((lib, syms, text_section(lib)))

    def agrees(name, addr):
        for lib, syms, (vaddr, size, ptr) in libs:
            if syms.get(name) != addr:
                return False
            if addr < SHLIB_DATA:
                off = ptr + addr - vaddr
                if not vaddr <= addr < vaddr + size or lib[off:off + 2] != b'\x4e\xf9':
                    return False
        return True

    kept = sorted((a, n) for n, a in entries.items() if agrees(n, a))
    left = sorted(set(entries) - {n for _, n in kept})
    print('/* Generated by sdk/tools/shlib-table.py: the entry points of /shlib/libc1_s at')
    print('   the same address in each A/UX version it was given. Left out: %s. */'
          % ', '.join(left))
    for addr, name in kept:
        print('PROVIDE(%s = %#x);' % (name, addr))
    print('%d entry points kept, %d left out' % (len(kept), len(left)), file=sys.stderr)


if __name__ == '__main__':
    main()
